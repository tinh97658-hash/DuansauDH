import { QueryTypes, type Transaction } from 'sequelize';
import type { Sequelize } from 'sequelize-typescript';
import type { AdmissionRecord } from '../database/models/plan/admission-record.model.js';
import { hasPaidAdmissionTuition } from './learner-study-status.js';
import { businessDate } from './study-leave-policy.js';
import { auditActor } from './membership-history.js';
import { returnUnpaidToApplication } from './unpaid-enrollment.js';

// Caller holds the learner mutex and record lock. Close invalid leave decisions
// and archive their evidence before returning the still-unpaid profile to intake.
export async function repairUnpaidStudyLeave(db: Sequelize, record: AdmissionRecord, actor: any, transaction: Transaction) {
  if (record.trainingLevel !== 'Thạc sĩ' || hasPaidAdmissionTuition(record)) return false;
  const leaves = await db.query<any>(`SELECT * FROM study_leaves WHERE admission_record_id=:id
    AND status IN ('pending','approved') ORDER BY id FOR UPDATE`, {
    replacements: { id: record.id }, type: QueryTypes.SELECT, transaction,
  });
  if (!leaves.length && !['Bảo lưu', 'Đang bảo lưu', 'Bảo lưu quá hạn'].includes(record.studyStatus || '')) return false;
  const reason = 'Hủy bảo lưu không hợp lệ do chưa nộp học phí; rút lớp và đưa về hồ sơ đầu vào.';
  for (const leave of leaves) {
    const withdrawals = await db.query(`SELECT * FROM course_offering_withdrawals WHERE study_leave_id=:id ORDER BY id FOR UPDATE`, {
      replacements: { id: leave.id }, type: QueryTypes.SELECT, transaction,
    });
    const extensions = (leave.extensions || []).map((extension: any) => extension.status === 'pending'
      ? { ...extension, status: 'cancelled', decisionNote: reason } : extension);
    const event = { action: 'unpaid_leave_cancelled', at: new Date().toISOString(), actorId: actor?.id || null,
      actor: auditActor(actor).name, note: reason, previousStatus: leave.status,
      previousDecision: { activatedAt: leave.activated_at, closedDate: leave.closed_date, decisionNote: leave.decision_note },
      withdrawals, previousExtensions: leave.extensions || [] };
    await db.query(`UPDATE study_leaves SET status='rejected',closed_date=:today,decision_note=:reason,
      extensions=CAST(:extensions AS jsonb),history=history || CAST(:event AS jsonb),updated_at=NOW() WHERE id=:id`, {
      replacements: { id: leave.id, today: businessDate(), reason, extensions: JSON.stringify(extensions), event: JSON.stringify([event]) }, transaction,
    });
    // Remove only the failures generated by the invalid leave. Original marks
    // remain in their gradebooks; full withdrawal snapshots stay in the event.
    await db.query('DELETE FROM course_offering_withdrawals WHERE study_leave_id=:id', {
      replacements: { id: leave.id }, transaction,
    });
  }
  await returnUnpaidToApplication(db, record, actor, reason, transaction, true);
  return true;
}
